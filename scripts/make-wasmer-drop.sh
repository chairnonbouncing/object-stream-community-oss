#!/usr/bin/env bash
# Assembles dist/wasmer-drop: a clean, upload-ready copy of the project with a
# prefilled .env (fresh AUTH_SECRET each run) and step-by-step deploy notes.
set -euo pipefail
cd "$(dirname "$0")/.."

OUT="dist/wasmer-drop"
rm -rf "$OUT"
mkdir -p "$OUT"

rsync -a \
  --exclude node_modules \
  --exclude .next \
  --exclude dist \
  --exclude .git \
  --exclude .claude \
  --exclude "prisma/dev.db*" \
  --exclude ".env" \
  --exclude ".env.local" \
  --exclude .DS_Store \
  ./ "$OUT/"

ADMIN_PASSWORD="${ADMIN_PASSWORD:?set ADMIN_PASSWORD}"
cat > "$OUT/.env" <<EOF
# Generated by scripts/make-wasmer-drop.sh — review before deploying.
# On a host with a persistent volume, point DATABASE_URL at it,
# e.g. file:/data/osc.db
DATABASE_URL="file:./dev.db"
AUTH_SECRET="$(openssl rand -base64 32)"
AUTH_TRUST_HOST="true"
ADMIN_USERNAME="admin"
ADMIN_PASSWORD="${ADMIN_PASSWORD}"
EOF

cat > "$OUT/DEPLOY-README.md" <<'EOF'
# Deploying Object Stream Community from this folder

This folder is the complete app source plus a prefilled `.env`
(admin login + a freshly generated session secret). Review `.env` first.

## Wasmer

```bash
# once: https://docs.wasmer.io/install
wasmer login
# from inside this folder:
wasmer deploy        # auto-detects Next.js, builds, prompts to create the app
```

- Copy the values from `.env` into the app's environment variables in the
  Wasmer dashboard (or the generated `app.yaml`) — env files are not uploaded
  automatically by every flow.
- **Database**: SQLite needs a persistent volume; attach one and set
  `DATABASE_URL=file:/<volume-path>/osc.db`. Without a volume the catalog
  resets on every redeploy. Wasmer can auto-attach **MySQL** instead — then
  change `provider = "mysql"` in `prisma/schema.prisma`, run
  `npx prisma migrate dev`, and use the injected connection string.
- After the first deploy, initialize the database once:
  `npx prisma migrate deploy && npx prisma db seed`
- Heads-up: Wasmer's Next.js template targets a workers-style JS runtime
  (WinterJS). This app needs full Node.js (Prisma, NextAuth, SQLite). If
  `wasmer deploy` can't run it on your plan, use the fallback below — the app
  itself needs no changes either way.

## Anywhere else (fallback that always works)

```bash
docker build -t osc . && docker run -p 3000:3000 -v osc-data:/app/prisma --env-file .env osc
```

or on any Node 18.18+ host:

```bash
npm ci
npx prisma migrate deploy && npx prisma db seed
npm run build && npm start
```

Sign in as `admin` with the password from `.env`, then change anything you
like from /admin.
EOF

echo "✔ built $OUT"
du -sh "$OUT" | awk '{print "  size: " $1}'
find "$OUT" -maxdepth 1 | sort | tail -n +2 | sed 's|.*/|  - |'
