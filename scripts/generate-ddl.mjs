// Regenerates lib/generated/ddl.ts from the Prisma schema. Runs as part of
// `npm run build:host` so the server can bootstrap a fresh SQLite database at
// startup on hosts where we don't control the start command (no CLI needed).
import { execSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";

const sql = execSync(
  "npx prisma migrate diff --from-empty --to-schema-datamodel prisma/schema.prisma --script",
  { encoding: "utf8" }
);

const file = `// AUTO-GENERATED by scripts/generate-ddl.mjs — do not edit by hand.
// Full SQLite DDL for the current Prisma schema.
export const DDL = ${JSON.stringify(sql)};
`;

mkdirSync("lib/generated", { recursive: true });
writeFileSync("lib/generated/ddl.ts", file);
console.log("✔ wrote lib/generated/ddl.ts");
